#!/usr/bin/env python3
"""
Susan Tumuhairwe site: the "sprig" signature artwork.

Generates ../site/css/art.css: small flat SVG shapes embedded as data URIs (so they work from file:// and
need no extra requests) and exposed as CSS classes/masks:
  --art-divider   leaf between two hairlines (heading underline; colour comes from the element's background via a mask)
  --art-branch    large leafy branch, faint line art in banners (colour comes from the element's background)
and the symbol markup for the small sprig mark that js/icons.js carries.
Run: python3 make_art.py
"""
import math, os, urllib.parse

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "site", "css", "art.css")
GOLD = "#c9a24a"


def uri(svg):
    return "url(\"data:image/svg+xml," + urllib.parse.quote(svg.replace("\n", ""), safe="/:=,;()' ") + "\")"


def bez(p, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = p
    u = 1 - t
    x = u**3*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t**3*x3
    y = u**3*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t**3*y3
    dx = 3*u*u*(x1-x0) + 6*u*t*(x2-x1) + 3*t*t*(x3-x2)
    dy = 3*u*u*(y1-y0) + 6*u*t*(y2-y1) + 3*t*t*(y3-y2)
    return x, y, math.degrees(math.atan2(dy, dx))


LEAF = "M0 0 C 5 -9 19 -12 30 -2 C 19 8 5 9 0 0 Z"      # one leaf, tip pointing +x, 30 long


def sprig(w, h, pts, ts, size, stem_w, fill="#000", extra=""):
    parts = [f'<path d="M{pts[0][0]} {pts[0][1]} C{pts[1][0]} {pts[1][1]} {pts[2][0]} {pts[2][1]} {pts[3][0]} {pts[3][1]}" fill="none" stroke="{fill}" stroke-width="{stem_w}" stroke-linecap="round"/>']
    for i, t in enumerate(ts):
        x, y, a = bez(pts, t)
        side = 1 if i % 2 == 0 else -1
        s = size * (1.0 - 0.35 * t)
        parts.append(f'<path d="{LEAF}" fill="{fill}" transform="translate({x:.1f} {y:.1f}) rotate({a + side * 42:.1f}) scale({s:.2f})"/>')
    x, y, a = bez(pts, 1)
    parts.append(f'<path d="{LEAF}" fill="{fill}" transform="translate({x:.1f} {y:.1f}) rotate({a:.1f}) scale({size * 0.62:.2f})"/>')
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{"".join(parts)}{extra}</svg>'


# 1. divider: hairline, leaf, hairline
divider = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 14"><path d="M0 7H38M58 7H96" stroke="#000" stroke-width="1.4"/><path d="M48 7 C 46 1 40 1 38 7 C 40 13 46 13 48 7 Z" fill="#000" transform="translate(10 0)"/></svg>'''
# 2. footer wave (scallops) 120x20 tile
wave = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 20" preserveAspectRatio="none"><path d="M0 20V12Q30 0 60 12T120 12V20Z" fill="#000"/></svg>'
# 3. header vine: thin sine line 48x8 tile
vine = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 8"><path d="M0 4Q12 0 24 4T48 4" fill="none" stroke="#000" stroke-width="1.4"/></svg>'
# 4. banner branch: a long, gently curved branch with leaves
branch = sprig(420, 280, [(10, 270), (120, 240), (220, 120), (400, 24)], [0.12, 0.2, 0.3, 0.38, 0.48, 0.58, 0.68, 0.78, 0.88], 1.35, 3.2)
# 5. the small mark (also in js/icons.js as #i-sprig, fill = currentColor)
mark = sprig(64, 64, [(10, 60), (22, 46), (34, 30), (52, 8)], [0.3, 0.5, 0.7], 0.62, 2.4, fill="currentColor")

css = f"""/* GENERATED by tools/make_art.py: do not edit by hand. Flat shapes only, no gradients. */
:root {{
  --art-divider: {uri(divider)};
  --art-branch:  {uri(branch)};
}}
"""
open(OUT, "w", encoding="utf-8").write(css)
print("wrote", os.path.normpath(OUT), len(css), "bytes")
print("MARK:", mark)
